#!/usr/bin/env rust-script
//! ```cargo
//! [dependencies]
//! chess = { package = "rust-chess", path = ".." }
//! ```

use std::{
    fs::File,
    io::{self, BufWriter, Write},
};

use chess::Scharnagl;

fn main() -> io::Result<()> {
    let file = File::create("src/board/SCHARNAGL-PREFIXES.rs")?;
    let mut writer = BufWriter::new(file);

    writeln!(writer, "// Generated by scripts/scharnagl-prefixes.rs.")?;
    writeln!(writer, "[")?;
    for (prefix, scharnagl) in Scharnagl::compute_prefixes() {
        writeln!(
            writer,
            "    ([0x{:02x}, 0x{:02x}, 0x{:02x}], Scharnagl({scharnagl})),",
            prefix[0], prefix[1], prefix[2]
        )?;
    }
    writeln!(writer, "]")
}
